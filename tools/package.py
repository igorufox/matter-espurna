#!/usr/bin/env python3
# The package of one chip ESPurna takes (tools/ci_build.sh for the release, tools/build.sh for a local build):
#
#   tools/package.py <chip> <matter-espurna> <connectedhomeip> <gn out dir> <libMatterApp.a> <package dir> [<zip>]
#
# <chip>: bk7231n or esp32
#   lib/libMatterApp.a
#   include/chip/gn/app/matter_requirements.h  what the library needs from the firmware's FreeRTOS, lwIP and mbedTLS:
#                               the firmware compiles <app/matter_requirements.h> with its own SDK flags, a mismatch
#                               stops its build
#   include/chip/gn/app/matter_chip_config.h  esp32: the CONFIG_* of connectedhomeip's ESP32 component the library was
#                               built with (its sdkconfig.h); the firmware includes it before the API headers
#   include/chip/gn/app/matter_abi.h  the sizes of the types the library shares with the firmware, as it was compiled
#                               (tools/abi.py from the ABI probe of the build; NM = the chip's nm)
#   include/chip/<root>/...     the headers of the library's API, each <root> one include folder:
#     src, include              connectedhomeip src/ and src/include/ (headers only)
#     app-common                connectedhomeip zzz_generated/app-common (the generated cluster headers:
#                               app-common/zap-generated/cluster-enums.h ...)
#     nlassert, nlio            the two header libraries of connectedhomeip's third_party
#     gen                       the build configuration headers GN wrote (gen/include of the build)
#     gn                        app/*.h (the project config), platform/ble/*.h (the BLE manager) and, bk7231n,
#                               external_platform/BK7231N/*.h of this repository
#   include/chip/flags.txt      "-I<root>" lines (relative to include/chip) and the "-D" defines of the library's code
#
# ESPurna's code on the Matter API (the identity of the board, matter_identity.cpp of the fork: one code with the
# ESP32) is compiled against exactly these headers and defines, so it sees the classes as the library was built.
# The zip has a fixed member order and timestamps: the same bytes for the same inputs.

import os
import re
import shutil
import subprocess
import sys
import zipfile

HEADERS = (".h", ".hpp", ".ipp", ".inc", ".def")

# what the headers of the API need (the build configuration headers of gen/); the rest of the library's defines
# (minimal mDNS, the BDK's CONFIG_IPV6) only concern its own sources
DEFINES = ("CHIP_HAVE_CONFIG_H=1",)


def copy_headers(src, dst):
    for root, dirs, files in os.walk(src):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for name in sorted(files):
            if name.endswith(HEADERS):
                path = os.path.join(root, name)
                target = os.path.join(dst, os.path.relpath(path, src))
                os.makedirs(os.path.dirname(target), exist_ok=True)
                shutil.copyfile(path, target)


def chip_config(chip, sdkconfig, output):
    """ESP32: the CONFIG_* of connectedhomeip's ESP32 component the library was built with (its Kconfig in the library's
    sdkconfig.h, gn/esp32): the headers of the API read them (pool sizes of the exchanges, timers, endpoints), the
    firmware's own sdkconfig.h does not have them. Forced (#undef first): a firmware value would change the layout"""
    names = set(re.findall(r"^\s*config\s+(\w+)",
                           open(os.path.join(chip, "config", "esp32", "components", "chip", "Kconfig"),
                                encoding="utf-8").read(), re.M))
    lines = ["/* generated by tools/package.py from the sdkconfig.h of the ESP32 library (gn/esp32) - do not edit",
             " * The options of connectedhomeip's ESP32 component the library was built with: include before any",
             " * header of the library's API */", "#pragma once", ""]
    for name, value in re.findall(r"^#define CONFIG_(\w+) (.+)$", open(sdkconfig, encoding="utf-8").read(), re.M):
        if name in names:
            lines += [f"#undef CONFIG_{name}", f"#define CONFIG_{name} {value}"]
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main(target, m, chip, out, lib, pkg, archive=None):
    if target not in ("bk7231n", "esp32"):
        raise SystemExit(f"package.py: unknown chip {target}")

    shutil.rmtree(pkg, ignore_errors=True)
    os.makedirs(os.path.join(pkg, "lib"))
    shutil.copyfile(lib, os.path.join(pkg, "lib", "libMatterApp.a"))
    os.makedirs(os.path.join(pkg, "include"))
    probes = [os.path.join(root, name) for root, _, files in os.walk(out) for name in files
              if "matter_abi_probe" in name and name.endswith(".o")]
    if len(probes) != 1:
        raise SystemExit(f"package.py: {len(probes)} ABI probe objects in {out}, expected 1")
    nm = os.environ.get("NM")
    if not nm:
        raise SystemExit("package.py: NM (the chip's nm) is required for matter_abi.h")

    headers = os.path.join(pkg, "include", "chip")
    roots = {
        "src": os.path.join(chip, "src"),
        "include": os.path.join(chip, "src", "include"),
        "app-common": os.path.join(chip, "zzz_generated", "app-common"),
        "nlassert": os.path.join(chip, "third_party", "nlassert", "repo", "include"),
        "nlio": os.path.join(chip, "third_party", "nlio", "repo", "include"),
        "gen": os.path.join(out, "gen", "include"),
    }
    for name, src in roots.items():
        copy_headers(src, os.path.join(headers, name))

    gn = os.path.join(headers, "gn")
    copy_headers(os.path.join(m, "gn", "app"), os.path.join(gn, "app"))
    # the BLE manager of the library (EXTERNAL_BLEMANAGERIMPL_HEADER <platform/ble/BLEManagerImpl.h> of both chips):
    # the firmware's matter module includes it through CHIPDeviceBuildConfig.h (20.11: missing, the module did not build)
    copy_headers(os.path.join(m, "gn", "platform"), os.path.join(gn, "platform"))
    if target == "esp32":
        chip_config(chip, os.path.join(m, "gn", "third_party", "esp32-config", "sdkconfig.h"),
                    os.path.join(gn, "app", "matter_chip_config.h"))
    # next to matter_requirements.h (app/), which includes it
    subprocess.run([sys.executable, os.path.join(m, "tools", "abi.py"), nm, probes[0],
                    os.path.join(gn, "app", "matter_abi.h")], check=True)
    if target == "bk7231n":
        copy_headers(os.path.join(m, "gn", "external_platform", "BK7231N"),
                     os.path.join(gn, "external_platform", "BK7231N"))

    with open(os.path.join(headers, "flags.txt"), "w", newline="\n") as f:
        for name in (*roots.keys(), "gn"):
            f.write(f"-I{name}\n")
        for define in DEFINES:
            f.write(f"-D{define}\n")

    if not archive:
        return

    names = []
    for root, dirs, files in os.walk(pkg):
        dirs.sort()
        for name in sorted(files):
            names.append(os.path.relpath(os.path.join(root, name), pkg).replace(os.sep, "/"))

    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name in names:
            info = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
            info.external_attr = 0o644 << 16
            with open(os.path.join(pkg, name), "rb") as f:
                z.writestr(info, f.read(), compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)


if __name__ == "__main__":
    main(*sys.argv[1:])
