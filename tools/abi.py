#!/usr/bin/env python3
# matter_abi.h of the release package from the ABI probe of a build (gn/app/matter_abi_probe.c):
#
#   tools/abi.py <nm command> <matter_abi_probe object> <out .h>
#
# Every abi_type_<name> / abi_value_<name> array of the probe has the size of the type / the value of the constant as
# the library was compiled; the header asserts the same of the firmware that compiles it (matter_requirements.h).
#   abi_type_struct_<tag>  -> sizeof(struct <tag>)
#   abi_type_<type>        -> sizeof(<type>)
#   abi_value_<name>       -> <name>; a <name>_1 holds <name> + 1 (a constant that may be 0)

import re
import shlex
import subprocess
import sys

LINE = re.compile(r"^[0-9a-fA-F]+\s+([0-9a-fA-F]+)\s+\w\s+abi_(type|value)_(\w+)$")


def main(nm, probe, output):
    text = subprocess.run(shlex.split(nm) + ["-S", "--defined-only", probe], check=True, capture_output=True, text=True).stdout
    items = []
    for line in text.splitlines():
        match = LINE.match(line.strip())
        if match:
            size, kind, name = int(match.group(1), 16), match.group(2), match.group(3)
            items.append((kind, name, size))
    if not items:
        raise SystemExit(f"abi.py: no abi_* symbols in {probe}")

    out = [
        "/* generated by tools/abi.py from the ABI probe of the library's build - do not edit",
        " * The sizes of the types and the constants the library shares with the firmware, as the library was compiled:",
        " * the firmware's SDK and config have to give the same (matter_requirements.h includes this). */",
        "#pragma once",
        "",
    ]
    for kind, name, size in sorted(items, key=lambda item: (item[0] != "value", item[1])):
        if kind == "type":
            expr = f"sizeof(struct {name[len('struct_'):]})" if name.startswith("struct_") else f"sizeof({name})"
            out.append(f'static_assert({expr} == {size}, "Matter library: {expr} is {size} in the library");')
        else:
            value = size
            if name.endswith("_1"):
                name, value = name[:-2], size - 1
            # a constant may carry a cast (FreeRTOS: ( ( TickType_t ) 500 )): compared by the compiler, not by #if
            out.append(f"#if !defined({name})")
            out.append(f'#error "Matter library: {name} is {value} in the library, the firmware has none"')
            out.append("#endif")
            out.append(f'static_assert(({name}) == {value}, "Matter library: {name} is {value} in the library");')
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:])
